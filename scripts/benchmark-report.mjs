#!/usr/bin/env node
/**
 * Turns contracts/benchmarks/*.json (written by the Foundry BenchmarkTest and hardhat/simulate.js)
 * into docs/EVALUATION.md — the tables for the performance-evaluation chapter.
 *
 *   node scripts/benchmark-report.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "contracts", "benchmarks");
const files = readdirSync(dir).filter((f) => f.endsWith(".json"));
const gas = files.filter((f) => !f.startsWith("live-")).map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")));
const live = files.filter((f) => f.startsWith("live-")).map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")));
const order = ["small_single_ward_10_pus", "medium_single_lga_30_wards", "large_five_lgas", "full_oyo_state"];
gas.sort((a, b) => order.indexOf(a.scenario) - order.indexOf(b.scenario));

const n = (v) => Number(v).toLocaleString("en-GB");
const gwei = 20; // assumed gas price for cost illustration
const ethUsd = 2500;
const cost = (g) => `${((Number(g) * gwei) / 1e9).toFixed(5)} ETH (~$${(((Number(g) * gwei) / 1e9) * ethUsd).toFixed(2)})`;

let md = `# Performance evaluation (generated)

Generated by \`scripts/benchmark-report.mjs\` from \`contracts/benchmarks/*.json\`. Gas figures come from the
Foundry benchmark suite (\`forge test --match-contract BenchmarkTest -vv\`, full state scale with
\`VOTECHAIN_FULL_SCALE=1\`), which executes the complete honest collation chain for each scenario.
Throughput and latency are derived for a public Ethereum-style network with a 30,000,000 gas block limit and
12-second blocks (Sepolia parameters); wall-clock numbers come from \`hardhat/simulate.js\` when present.

## Scenarios (Section 3.11.2)

| Scenario | LGAs | Wards | Polling units | Parties | Collation-flow gas | Blocks needed (throughput bound) | Time at 12 s/block |
|---|---:|---:|---:|---:|---:|---:|---:|
`;
for (const s of gas) {
  md += `| ${s.scenario} | ${s.lgas} | ${s.wards} | ${n(s.pollingUnits)} | ${s.parties} | ${n(s.collationFlowGasTotal)} | ${n(s.blocksNeededThroughputBound)} | ${n(s.throughputBoundSeconds)} s (${(s.throughputBoundSeconds / 60).toFixed(1)} min) |\n`;
}
md += `
"Collation-flow gas" counts every operational transaction (submissions, signatures, collation confirmations,
audit and declaration) and excludes one-off deployment and registration costs.

## Gas cost per transaction type

Averages over every call of that type in the largest scenario available (${gas.at(-1)?.scenario}). The
illustrative cost column assumes ${gwei} gwei and ETH = $${ethUsd}; on the Sepolia testnet the cost is nil.

| Transaction | Calls | Avg gas | Min | Max | Illustrative cost per call |
|---|---:|---:|---:|---:|---|
`;
const big = gas.at(-1);
if (big) {
  for (const [name, t] of Object.entries(big.txTypes).sort()) {
    md += `| \`${name}\` | ${n(t.count)} | ${n(t.avgGas)} | ${n(t.minGas)} | ${n(t.maxGas)} | ${cost(t.avgGas)} |\n`;
  }
}
md += `
## Throughput and latency

| Scenario | Avg submitResult gas | Submissions per block | Submissions per minute | Critical-path blocks | End-to-end latency lower bound |
|---|---:|---:|---:|---:|---:|
`;
for (const s of gas) {
  md += `| ${s.scenario} | ${n(s.txTypes["po.submitResult"].avgGas)} | ${s.submissionsPerBlock} | ${s.submissionsPerMinute} | ${s.criticalPathBlocks} | ${s.latencyLowerBoundSeconds} s |\n`;
}
md += `
The critical path is the shortest dependent sequence for one result to travel from a polling unit to the
declaration: submit → PU signatures → ward confirmation → ward signatures → LGA confirmation → LGA signatures →
state confirmation → state signatures → audit signature → declaration (10 blocks). Because polling units are
independent, the throughput bound — not the critical path — dominates at Oyo State scale: the full 4,700-unit
election fits in about ${big ? n(big.blocksNeededThroughputBound) : "?"} blocks of 30M gas, i.e. roughly
${big ? (big.throughputBoundSeconds / 60).toFixed(0) : "?"} minutes of block space, once every stakeholder has
acted.
`;
if (live.length) {
  md += `
## Live simulation (wall-clock, local node)

| Scale | Polling units | Wards | Config time | PU phase | Submissions/min (measured) | End-to-end latency | Total gas |
|---|---:|---:|---:|---:|---:|---:|---:|
`;
  for (const s of live) {
    md += `| ${s.scale} | ${s.pollingUnits} | ${s.wards} | ${s.configurationSeconds.toFixed(1)} s | ${s.pollingUnitPhaseSeconds.toFixed(1)} s | ${s.submissionsPerMinute} | ${s.endToEndLatencySeconds.toFixed(1)} s | ${n(s.totalGasUsed)} |\n`;
  }
}
md += `
## Deployment cost

| Contract | Deployment gas |
|---|---:|
`;
if (big) for (const [name, t] of Object.entries(big.txTypes).filter(([k]) => k.startsWith("deploy."))) md += `| ${name.replace("deploy.", "")} | ${n(t.avgGas)} |\n`;

writeFileSync(join(root, "docs", "EVALUATION.md"), md);
console.log(`wrote docs/EVALUATION.md from ${files.length} benchmark file(s)`);
